const fs=require('fs')
const path=require('path')
const {chromium}=require('playwright')
;(async()=>{
  const root=path.resolve(__dirname,'../../..'),out=path.join(root,'output/p1-rrf')
  fs.mkdirSync(out,{recursive:true})
  const auth=JSON.parse(fs.readFileSync(path.join(root,'.auth/p1-rrf/credentials.json'),'utf8'))
  const browser=await chromium.launch({channel:'msedge',headless:true})
  const page=await browser.newPage({viewport:{width:1440,height:1000}})
  const checks=[]
  const pass=name=>{checks.push(name);console.log('PASS',name)}
  await page.goto('http://127.0.0.1:10087/#/pages/index/index')
  await page.locator('input[placeholder="请输入邮箱"]').fill(auth.email)
  await page.locator('input[placeholder="请输入密码"]').fill(auth.password)
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await page.getByText('P1 · RRF 验收空间',{exact:true}).first().click()
  await page.getByText('检索调试',{exact:true}).first().click()
  const query=page.getByLabel('问题',{exact:true}),mode=page.getByLabel('检索方式')
  const search=page.getByRole('button',{name:'开始检索',exact:true})
  await mode.selectOption('hybrid');await query.fill('v2.7.4');await search.click()
  await page.getByRole('heading',{name:'RRF 融合',exact:true}).waitFor()
  const panels=page.locator('.v2-hybrid-grid > .v2-panel')
  if(await panels.count()!==3)throw Error('Missing three actual branch panels')
  for(const title of ['向量召回','关键词召回','RRF 融合'])await page.getByRole('heading',{name:title,exact:true}).waitFor()
  await page.screenshot({path:path.join(out,'rrf-desktop.png'),fullPage:true});pass('Three actual branch rankings and source scores')
  await page.locator('.v2-hybrid-grid .v2-evidence').first().click()
  await page.getByRole('heading',{name:'来源定位',exact:true}).waitFor();pass('Branch source click reveals live source')
  await query.fill('UNKNOWN_CODE_78219');await search.click()
  await page.getByRole('heading',{name:'RRF 融合',exact:true}).waitFor()
  if(!(await panels.nth(1).innerText()).includes('本路没有可用片段'))throw Error('Keyword empty branch is not explicit')
  pass('Unknown identifier leaves keyword branch empty without fake matches')
  await page.route('**/retrieval-runs',async route=>{await new Promise(resolve=>setTimeout(resolve,900));try{await route.continue()}catch{}})
  await query.fill('SCOPE_CHANGED');await search.click()
  await page.getByText('正在查找当前空间的相关片段…').waitFor()
  await mode.selectOption('dense');await page.waitForTimeout(1400)
  if(await page.locator('.v2-hybrid-grid').count())throw Error('Canceled fusion result leaked')
  await page.unroute('**/retrieval-runs');pass('Mode change cancels all stale comparison lanes')
  await mode.selectOption('hybrid');await search.click()
  await page.getByRole('heading',{name:'RRF 融合',exact:true}).waitFor()
  await page.setViewportSize({width:390,height:844})
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow')
  const source=page.getByRole('button',{name:'用此问题去问答',exact:true})
  await source.scrollIntoViewIfNeeded()
  const box=await source.boundingBox();if(!box||box.y+box.height>844)throw Error('Source button obstructed')
  await page.screenshot({path:path.join(out,'rrf-mobile.png'),fullPage:true});pass('390px stacked lanes and reachable source action')
  await page.setViewportSize({width:1440,height:1000})
  await source.click();await page.getByText('本次问答使用混合检索 · RRF').waitFor()
  const request=page.waitForRequest(r=>r.method()==='POST'&&/\/owner\/conversations\/[^/]+\/messages$/.test(r.url()))
  await page.getByRole('button',{name:'发送问题',exact:true}).click()
  if((await request).postDataJSON().strategy!=='hybrid')throw Error('Handoff lost hybrid strategy')
  await page.getByRole('button',{name:'发送问题',exact:true}).waitFor({timeout:180000})
  pass('Real owner generation receives explicit hybrid handoff')
  await page.getByRole('button',{name:'恢复向量检索',exact:true}).click()
  if(await page.getByText('本次问答使用混合检索 · RRF').count())throw Error('Dense reset failed')
  pass('Dense baseline can be restored')
  await page.getByText('评测',{exact:true}).first().click()
  await page.getByLabel('评测检索方式').selectOption('hybrid')
  if(await page.getByLabel('评测检索方式').inputValue()!=='hybrid')throw Error('Evaluation strategy cannot be selected')
  pass('Evaluation exposes explicit hybrid and dense strategy choices')
  fs.writeFileSync(path.join(out,'ui-check.json'),JSON.stringify({status:'PASSED',checks,browser:'real headless Edge',mocked_success:false,controlled_delay:true},null,2))
  await browser.close()
})().catch(error=>{console.error(error.message);process.exit(1)})
