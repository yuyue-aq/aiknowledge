const fs = require('fs')
const path = require('path')
const { chromium } = require('playwright')

;(async () => {
  const root = path.resolve(__dirname, '../../..')
  const auth = JSON.parse(fs.readFileSync(path.join(root, '.auth/p1-preview/credentials.json'), 'utf8'))
  const out = path.join(root, 'output/p1-bm25'); fs.mkdirSync(out, { recursive: true })
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  page.on('requestfailed', r => console.log('FAILED',r.url().split('?')[0],r.failure()?.errorText))
  page.on('response',r=>{if(r.url().includes('/api/'))console.log('API',r.status(),r.url().split('?')[0])})
  await page.goto('http://127.0.0.1:10087/#/pages/index/index')
  await page.locator('input[placeholder="请输入邮箱"]').fill(auth.email)
  await page.locator('input[placeholder="请输入密码"]').fill(auth.password)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.waitForTimeout(2500)
  console.log((await page.locator('body').innerText()).slice(0,2200))
  await page.screenshot({path:path.join(out,'login-state.png'),fullPage:true})
  await page.getByText('P1 · BM25 人工验收空间', { exact: true }).first().waitFor()
  await page.getByText('P1 · BM25 人工验收空间', { exact: true }).first().click()
  await page.getByText('检索调试', { exact: true }).first().click()
  await page.getByLabel('检索方式').selectOption('bm25')
  const query = page.getByLabel('问题', { exact: true })
  const search = page.getByRole('button', { name: '开始检索', exact: true })
  await query.fill('SCOPE_CHANGED')
  await search.click()
  await page.getByText('BM25 分数', { exact: false }).first().waitFor()
  if (!(await page.locator('body').innerText()).includes('01-公开范围.txt')) throw new Error('Missing real source')
  await page.screenshot({ path: path.join(out, 'bm25-desktop.png'), fullPage: true })
  const buttonBox = await search.boundingBox(), formBox = await page.locator('form.v2-query').boundingBox()
  if (buttonBox.x + buttonBox.width > formBox.x + formBox.width + 1) throw new Error('Query button overflows form')
  await page.getByRole('button', { name: '清空检索问题' }).click()
  if (await query.inputValue() !== '') throw new Error('Clear failed')
  if (!(await query.evaluate(node => node === document.activeElement))) throw new Error('Clear focus failed')
  await search.click()
  await page.getByRole('alert').filter({ hasText: '请输入问题' }).waitFor()
  await query.fill('UNKNOWN_CODE_78219'); await query.press('Enter')
  await page.getByText('没有匹配关键词的片段').waitFor()
  await page.route('**/retrieval-runs', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ code: 'RETRIEVAL_UNAVAILABLE', message: '关键词检索暂时不可用，请稍后重试。' }) }))
  await query.fill('SCOPE_CHANGED'); await search.click()
  await page.getByRole('alert').filter({ hasText: '关键词检索暂时不可用' }).waitFor()
  await page.unroute('**/retrieval-runs')
  await search.click(); await page.getByText('BM25 分数', { exact: false }).first().waitFor()
  await page.route('**/retrieval-runs', async route => {
    await new Promise(resolve => setTimeout(resolve, 900))
    try { await route.continue() } catch { /* A canceled search may end before forwarding. */ }
  })
  const stableWidth = (await search.boundingBox()).width
  await query.fill('SCOPE_CHANGED'); await search.click()
  await page.getByText('正在查找当前空间的相关片段…').waitFor()
  const busyWidth = (await page.getByRole('button', { name: '正在检索…', exact: true }).boundingBox()).width
  if (Math.abs(stableWidth - busyWidth) > 1) throw new Error('Busy button width changed')
  await page.getByLabel('检索方式').selectOption('dense')
  await page.waitForTimeout(1100)
  if (await page.locator('.v2-evidence').count() !== 0) throw new Error('Canceled BM25 result overwrote changed strategy')
  await page.unroute('**/retrieval-runs')
  await page.getByLabel('检索方式').selectOption('bm25')
  await search.click(); await page.getByText('BM25 分数', { exact: false }).first().waitFor()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: path.join(out, 'bm25-mobile.png'), fullPage: true })
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  if (overflow) throw new Error('Mobile horizontal overflow')
  await page.getByLabel('检索方式').focus()
  await page.keyboard.press('Home'); await page.keyboard.press('Enter')
  if (await page.getByLabel('检索方式').inputValue() !== 'dense') throw new Error('Native select keyboard failed')
  await page.getByLabel('检索方式').selectOption('bm25')
  await query.fill('v2.7.4'); await search.click()
  await page.getByText('BM25 分数', { exact: false }).first().waitFor()
  fs.writeFileSync(path.join(out, 'ui-check.json'), JSON.stringify({ status: 'PASSED', browser: 'real headless Edge', mocked_success: false, controlled_failure: 'HTTP503 for UI error-state check; delayed forwarding for loading/stale-state check', checks: ['real login', 'real keyword source', 'score semantics', 'clear and focus', 'empty validation', 'no match', 'Enter submit', 'network error and retry', 'loading width stable', 'canceled strategy result ignored', '390px responsive', 'native select keyboard'] }, null, 2))
  console.log('Real H5 UI checks PASSED')
  await browser.close()
})().catch(error => { console.error(error.message); process.exit(1) })
