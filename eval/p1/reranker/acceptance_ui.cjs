const fs=require('fs'),path=require('path'),assert=require('assert/strict')
const {chromium}=require('playwright')
;(async()=>{
  const root=path.resolve(__dirname,'../../..'),out=path.join(root,'output/p1-reranker/acceptance-20261008')
  fs.mkdirSync(out,{recursive:true})
  const auth=JSON.parse(fs.readFileSync(path.join(root,'.auth/p1-c-acceptance/credentials.json'),'utf8'))
  const state=JSON.parse(fs.readFileSync(path.join(root,'.auth/p1-c-acceptance/state.json'),'utf8'))
  const browser=await chromium.launch({channel:'msedge',headless:true}),page=await browser.newPage({viewport:{width:1440,height:1000}})
  page.setDefaultTimeout(30000)
  const checks=[],runs=[],retrievals=[],answers=[],pass=name=>{checks.push(name);console.log('PASS',name)}
  try{
    await page.goto('http://127.0.0.1:10087/#/pages/index/index')
    await page.locator('input[placeholder="请输入邮箱"]').fill(auth.email);await page.locator('input[placeholder="请输入密码"]').fill(auth.password)
    await page.getByRole('button',{name:'登录',exact:true}).click();await page.getByText(state.space_name,{exact:true}).first().click()
    await page.getByText('检索调试',{exact:true}).first().click()
    const mode=page.getByLabel('检索方式'),query=page.getByLabel('问题',{exact:true}),search=page.getByRole('button',{name:'开始检索',exact:true})
    await mode.selectOption('hybrid_rerank')
    for(const [q,doc,fact] of [['青岚的访客能否拿到原始文件？','01-青岚规则.md','不允许下载'],['星桥谁负责批准范围变更？','02-星桥规则.md','空间拥有者'],['云栈停用后资料保存多久？','03-云栈规则.md','90天']]){
      await query.fill(q)
      const response=page.waitForResponse(r=>r.request().method()==='POST'&&r.url().endsWith('/retrieval-runs'))
      await search.click();const result=await (await response).json();assert.equal(result.strategy,'hybrid_rerank')
      assert.equal(result.items[0].document_name,doc);assert.ok(result.items[0].content.includes(fact));retrievals.push(result)
      await page.getByRole('heading',{name:'重排后 · 真实模型',exact:true}).waitFor({timeout:180000})
      assert.equal(await page.locator('.v2-rerank-grid > .v2-panel').count(),2)
      await page.locator('.v2-rerank-grid > .v2-panel').nth(1).locator('.v2-evidence').first().click()
      assert.ok((await page.locator('.v2-source-text').innerText()).includes(fact))
    }
    pass('Three specified questions: correct service, real scores/ranks and complete current source')
    await page.screenshot({path:path.join(out,'desktop.png'),fullPage:true})
    await page.getByRole('button',{name:'清空检索问题',exact:true}).click()
    assert.equal(await query.inputValue(),'');assert.ok(await query.evaluate(el=>el===document.activeElement))
    await search.click();await page.getByRole('alert').filter({hasText:'请输入问题'}).waitFor()
    pass('Clear returns focus and empty question shows validation')
    await page.route('**/retrieval-runs',r=>r.fulfill({status:503,contentType:'application/json',body:JSON.stringify({code:'RERANK_UNAVAILABLE',message:'本地重排模型暂时不可用，请稍后重试。'})}))
    await query.fill('青岚测试版可以试用多少天？');await search.click()
    await page.getByRole('alert').filter({hasText:'本地重排模型暂时不可用'}).waitFor()
    await page.unroute('**/retrieval-runs');await search.click()
    await page.getByRole('heading',{name:'重排后 · 真实模型',exact:true}).waitFor({timeout:180000})
    pass('Controlled error clearly shown; retry uses real model')
    await page.route('**/retrieval-runs',async route=>{await new Promise(r=>setTimeout(r,1000));try{await route.continue()}catch{}})
    await search.click();await page.getByText('正在查找当前空间的相关片段…').waitFor()
    await mode.selectOption('hybrid');await page.waitForTimeout(1600);assert.equal(await page.locator('.v2-rerank-grid').count(),0)
    await page.unroute('**/retrieval-runs');await mode.selectOption('hybrid_rerank');await search.click()
    await page.getByRole('heading',{name:'重排后 · 真实模型',exact:true}).waitFor({timeout:180000})
    pass('Changing parameters cancels stale results in both columns')
    await page.getByLabel('Top K',{exact:true}).selectOption('3');assert.equal(await page.locator('.v2-rerank-grid').count(),0)
    await search.click();await page.getByRole('heading',{name:'重排后 · 真实模型',exact:true}).waitFor({timeout:180000})
    await query.fill('青岚试用时间是多少天？');assert.equal(await page.locator('.v2-rerank-grid').count(),0)
    await search.click();await page.getByRole('heading',{name:'重排后 · 真实模型',exact:true}).waitFor({timeout:180000})
    pass('Top K and query edits invalidate both old ranking columns')
    await page.setViewportSize({width:390,height:844});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
    const panels=page.locator('.v2-rerank-grid > .v2-panel'),first=await panels.nth(0).boundingBox(),second=await panels.nth(1).boundingBox()
    assert.ok(second.y>=first.y+first.height-1)
    const ask=page.getByRole('button',{name:'用此问题去问答',exact:true});await ask.scrollIntoViewIfNeeded()
    await page.screenshot({path:path.join(out,'mobile.png'),fullPage:true});pass('390px panels stack, no overflow and source/ask remain reachable')
    await page.setViewportSize({width:1440,height:1000});await ask.click()
    await page.getByText('本次问答使用混合检索 + 模型重排').waitFor()
    async function send(q){
      await page.getByLabel('输入你的问题').fill(q)
      const requested=page.waitForRequest(r=>r.method()==='POST'&&/\/owner\/conversations\/[^/]+\/messages$/.test(r.url()))
      await page.getByRole('button',{name:'发送问题',exact:true}).click();const request=await requested;assert.equal(request.postDataJSON().strategy,'hybrid_rerank')
      assert.ok(await page.getByRole('button',{name:'恢复向量检索',exact:true}).isDisabled())
      await page.getByRole('button',{name:'发送问题',exact:true}).waitFor({timeout:180000})
      const body=await page.locator('body').innerText();answers.push({question:q,page_text:body});return body
    }
    assert.ok((await send('青岚测试版可以试用多少天？')).includes('17天'))
    assert.ok(await page.getByRole('button',{name:'查看原文依据'}).count() || await page.locator('.citation-button').count() || (await page.locator('body').innerText()).includes('01-青岚规则.md'))
    const refusal=await send('青岚的真实公网地址是什么？');assert.ok(refusal.includes('资料不足')||refusal.includes('没有足够依据')||refusal.includes('资料未提供'))
    await page.screenshot({path:path.join(out,'answers.png'),fullPage:true})
    await page.getByRole('button',{name:'恢复向量检索',exact:true}).click();assert.equal(await page.getByText('本次问答使用混合检索 + 模型重排').count(),0)
    pass('Real 17-day cited answer, unknown-address refusal, busy lock and Dense restore')
    await page.getByText('评测',{exact:true}).first().click()
    for(const strategy of ['hybrid','hybrid_rerank']){
      await page.getByLabel('运行题集版本').selectOption(state.version_id);await page.getByLabel('评测检索方式').selectOption(strategy)
      const dispatched=page.waitForResponse(r=>r.request().method()==='POST'&&r.url().includes('/runs/async'))
      await page.getByRole('button',{name:'运行题集',exact:true}).click();const run=await (await dispatched).json();runs.push(run)
      await page.getByRole('heading',{name:'运行完成',exact:true}).waitFor({timeout:180000})
      assert.ok((await page.locator('body').innerText()).includes('已完成 3 / 3 题'))
      await page.getByRole('button',{name:'返回题集',exact:true}).click()
    }
    pass('UI dispatches same frozen three cases; both real Worker runs complete')
    await page.getByRole('button',{name:'基线与复测对比',exact:true}).click()
    await page.getByLabel('基线',{exact:true}).selectOption(runs[0].id);await page.getByLabel('复测',{exact:true}).selectOption(runs[1].id)
    await page.getByRole('button',{name:'生成对比',exact:true}).click();await page.getByRole('heading',{name:'逐题变化',exact:true}).waitFor()
    assert.ok((await page.locator('body').innerText()).includes('资料清单一致'))
    await page.screenshot({path:path.join(out,'comparison.png'),fullPage:true});pass('Same-version comparison renders actual paired results')
    fs.writeFileSync(path.join(out,'ui.json'),JSON.stringify({status:'PASSED',checks,runs,answers,retrievals,browser:'real Edge',mocked_success:false,controlled_failure:'503 and delayed forwarding only'},null,2))
  }catch(error){
    await page.screenshot({path:path.join(out,'failure.png'),fullPage:true}).catch(()=>{})
    fs.writeFileSync(path.join(out,'ui.json'),JSON.stringify({status:'FAILED',checks,error:error.message,runs},null,2));throw error
  }finally{await browser.close()}
})().catch(error=>{console.error(error.message);process.exit(1)})
