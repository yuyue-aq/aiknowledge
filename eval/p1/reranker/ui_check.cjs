const fs=require('fs'),path=require('path')
const {chromium}=require('playwright')
;(async()=>{
  const root=path.resolve(__dirname,'../../..'),out=path.join(root,'output/p1-reranker/ui')
  fs.mkdirSync(out,{recursive:true})
  const auth=JSON.parse(fs.readFileSync(path.join(root,'.auth/p1-reranker/credentials.json'),'utf8'))
  const browser=await chromium.launch({channel:'msedge',headless:true}),page=await browser.newPage({viewport:{width:1440,height:1000}})
  const checks=[],pass=name=>{checks.push(name);console.log('PASS',name)}
  await page.goto('http://127.0.0.1:10087/#/pages/index/index')
  await page.locator('input[placeholder="请输入邮箱"]').fill(auth.email);await page.locator('input[placeholder="请输入密码"]').fill(auth.password)
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await page.getByText('P1 · 真实重排验收空间',{exact:true}).first().click();await page.getByText('检索调试',{exact:true}).first().click()
  const mode=page.getByLabel('检索方式'),query=page.getByLabel('问题',{exact:true}),search=page.getByRole('button',{name:'开始检索',exact:true})
  await mode.selectOption('hybrid_rerank');await query.fill('青岚的访客可以下载原文件吗？');await search.click()
  await page.getByRole('heading',{name:'重排后 · 真实模型',exact:true}).waitFor({timeout:180000})
  if(await page.locator('.v2-rerank-grid > .v2-panel').count()!==2)throw Error('Not two actual comparison panels')
  if(!(await page.locator('.v2-rerank-grid > .v2-panel').nth(1).innerText()).includes('原排名'))throw Error('No actual rank provenance')
  await page.screenshot({path:path.join(out,'rerank-desktop.png'),fullPage:true});pass('Real pinned model before/after scores and ranks')
  await page.locator('.v2-rerank-grid .v2-evidence').first().click();await page.getByRole('heading',{name:'来源定位',exact:true}).waitFor()
  pass('Current source readable')
  await page.getByRole('button',{name:'清空检索问题',exact:true}).click();await search.click();await page.getByRole('alert').filter({hasText:'请输入问题'}).waitFor()
  pass('Clear and empty validation')
  await page.route('**/retrieval-runs',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({code:'RERANK_UNAVAILABLE',message:'本地重排模型暂时不可用，请稍后重试。'})}))
  await query.fill('青岚试用时间多少天？');await search.click();await page.getByRole('alert').filter({hasText:'本地重排模型暂时不可用'}).waitFor()
  await page.unroute('**/retrieval-runs');await search.click();await page.getByRole('heading',{name:'重排后 · 真实模型',exact:true}).waitFor({timeout:180000})
  pass('Controlled model error and real retry')
  await page.route('**/retrieval-runs',async route=>{await new Promise(resolve=>setTimeout(resolve,900));try{await route.continue()}catch{}})
  await search.click();await page.getByText('正在查找当前空间的相关片段…').waitFor();await mode.selectOption('hybrid')
  await page.waitForTimeout(1400);if(await page.locator('.v2-rerank-grid').count())throw Error('Stale model result rendered')
  await page.unroute('**/retrieval-runs');pass('Changing mode clears stale reranking')
  await mode.selectOption('hybrid_rerank');await search.click();await page.getByRole('heading',{name:'重排后 · 真实模型',exact:true}).waitFor({timeout:180000})
  await page.setViewportSize({width:390,height:844})
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile horizontal overflow')
  const ask=page.getByRole('button',{name:'用此问题去问答',exact:true});await ask.scrollIntoViewIfNeeded()
  await page.screenshot({path:path.join(out,'rerank-mobile.png'),fullPage:true});pass('390px stacked panels and reachable source')
  await page.setViewportSize({width:1440,height:1000});await ask.click()
  await page.getByText('本次问答使用混合检索 + 模型重排').waitFor()
  const requested=page.waitForRequest(r=>r.method()==='POST'&&/\/owner\/conversations\/[^/]+\/messages$/.test(r.url()))
  await page.getByRole('button',{name:'发送问题',exact:true}).click()
  if((await requested).postDataJSON().strategy!=='hybrid_rerank')throw Error('Generation handoff lost reranking')
  if(!await page.getByRole('button',{name:'恢复向量检索',exact:true}).isDisabled())throw Error('Pending generation mode mutable')
  await page.getByRole('button',{name:'发送问题',exact:true}).waitFor({timeout:180000})
  await page.getByRole('button',{name:'恢复向量检索',exact:true}).click();pass('Model generation handoff, busy mode lock and Dense restore')
  await page.getByText('评测',{exact:true}).first().click();await page.getByLabel('评测检索方式').selectOption('hybrid_rerank')
  pass('Evaluation model strategy selectable')
  fs.writeFileSync(path.join(out,'ui-check.json'),JSON.stringify({status:'PASSED',checks,browser:'real Edge',mocked_success:false,controlled_failure:'HTTP503 and delayed forwarding'},null,2))
  await browser.close()
})().catch(error=>{console.error(error.message);process.exit(1)})
